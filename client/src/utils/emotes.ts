// Fast lookup maps for emotes by name (case-insensitive) and code (with or without colons)
export const EMOTE_MAP = new Map<string, EmoteItem>();
SEVEN_TV_EMOTES.forEach((emote) => {
  EMOTE_MAP.set(emote.name.toLowerCase(), emote);
  EMOTE_MAP.set(emote.code.toLowerCase(), emote);
  // Also support bare without colons e.g. "catJam"
  const bare = emote.code.replace(/^:|:$/g, '').toLowerCase();
  EMOTE_MAP.set(bare, emote);
});

export function findEmote(token: string): EmoteItem | undefined {
  const clean = token.trim().toLowerCase();
  return EMOTE_MAP.get(clean);
}

// Helpers for Rich Link Previews
export function extractYouTubeId(url: string): string | null {
  try {
    const parsed = new URL(url);
    if (parsed.hostname.includes('youtube.com')) {
      return parsed.searchParams.get('v');
    }
    if (parsed.hostname === 'youtu.be') {
      return parsed.pathname.slice(1).split('?')[0];
    }
  } catch {
    // ignore
  }
  return null;
}

export function extractTwitchChannel(url: string): { channel: string; isClip?: boolean; isVideo?: boolean } | null {
  try {
    const parsed = new URL(url);
    if (parsed.hostname.includes('twitch.tv')) {
      const parts = parsed.pathname.split('/').filter(Boolean);
      if (parts.length === 1 && !['directory', 'p', 'videos', 'downloads'].includes(parts[0].toLowerCase())) {
        return { channel: parts[0] };
      }
      if (parts.length >= 2 && parts[0].toLowerCase() === 'videos') {
        return { channel: `Видео #${parts[1]}`, isVideo: true };
      }
      if (parts.length >= 2 && parts[0].toLowerCase() === 'clip') {
        return { channel: `Клип: ${parts[1]}`, isClip: true };
      }
      if (parts.length >= 1) {
        return { channel: parts[0] };
      }
    }
  } catch {
    // ignore
  }
  return null;
}

export function extractTelegramInfo(url: string): { handle: string; isPost?: boolean } | null {
  try {
    const parsed = new URL(url);
    if (parsed.hostname === 't.me' || parsed.hostname === 'telegram.me') {
      const parts = parsed.pathname.split('/').filter(Boolean);
      if (parts.length >= 1) {
        return { handle: parts[0], isPost: parts.length > 1 };
      }
    }
  } catch {
    // ignore
  }
  return null;
}

export function extractGitHubInfo(url: string): { owner: string; repo?: string } | null {
  try {
    const parsed = new URL(url);
    if (parsed.hostname.includes('github.com')) {
      const parts = parsed.pathname.split('/').filter(Boolean);
      if (parts.length >= 2) {
        return { owner: parts[0], repo: parts[1] };
      }
      if (parts.length === 1) {
        return { owner: parts[0] };
      }
    }
  } catch {
    // ignore
  }
  return null;
}

export function isImageUrl(url: string): boolean {
  return /\.(jpeg|jpg|gif|png|webp|svg)(\?.*)?$/i.test(url);
}

export function getDomainFromUrl(url: string): string {
  try {
    const parsed = new URL(url);
    return parsed.hostname.replace(/^www\./, '');
  } catch {
    return 'link';
  }
}

export function getFaviconUrl(url: string): string {
  const domain = getDomainFromUrl(url);
  return `https://www.google.com/s2/favicons?domain=${domain}&sz=64`;
}
