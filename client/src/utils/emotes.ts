// Map by code and lowercase name for instant lookup
export const EMOTE_MAP = new Map<string, EmoteItem>();
SEVEN_TV_EMOTES.forEach((e) => {
  EMOTE_MAP.set(e.code.toLowerCase(), e);
  EMOTE_MAP.set(`:${e.name.toLowerCase()}:`, e);
  EMOTE_MAP.set(e.name.toLowerCase(), e);
});

export function findEmote(token: string): EmoteItem | undefined {
  const clean = token.trim().toLowerCase();
  return EMOTE_MAP.get(clean);
}

// YouTube URL parser
export function extractYouTubeId(url: string): string | null {
  const match = url.match(
    /(?:https?:\/\/)?(?:www\.)?(?:youtube\.com\/(?:watch\?v=|shorts\/|embed\/)|youtu\.be\/)([a-zA-Z0-9_-]{11})/i
  );
  return match ? match[1] : null;
}

// Direct Image URL detection
export function isImageUrl(url: string): boolean {
  return (
    /\.(jpeg|jpg|gif|png|webp|svg)(\?.*)?$/i.test(url) ||
    /i\.imgur\.com/i.test(url) ||
    /cdn\.discordapp\.com\/attachments/i.test(url)
  );
}

// Extract domain name (e.g. "youtube.com", "github.com", "vk.com")
export function getDomainFromUrl(url: string): string {
  try {
    const parsed = new URL(url);
    return parsed.hostname.replace(/^www\./, '');
  } catch {
    return 'link';
  }
}
